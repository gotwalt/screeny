//! sRGB8 -> panel-level lookup.
//!
//! Everything upstream of here is sRGB 8-bit (`docs/design/architecture.md`).
//! An LED driven by binary-code modulation is, to a good approximation,
//! **linear in duty cycle**: a BCM value of 32/63 emits about half the light
//! of 63/63. sRGB is not linear in light, so writing sRGB codes straight into
//! the framebuffer — which is what the bring-up spike did — makes the whole
//! ramp far too bright in the shadows and compresses the highlights into
//! nothing. That is the "mid-grey is blown out" the card is asking about.
//!
//! So the table below is the sRGB electro-optical transfer function,
//!
//! ```text
//! L = c/12.92                      for c <= 0.04045
//! L = ((c + 0.055)/1.055)^2.4      otherwise
//! ```
//!
//! evaluated at each of the 256 sRGB codes and scaled to the panel's range.
//! No float and no `powf` on the device: this is a generated constant. The
//! generator is four lines of Python and is reproduced in the doc comment on
//! [`SRGB_TO_Q`] so the table can be regenerated and checked.
//!
//! # Why the table is 16x too big
//!
//! The panel has [`LEVELS`] = 64 duty levels (6 bit-planes). Quantising the
//! EOTF to 64 levels sends **34 of the 256 sRGB codes to zero** — everything
//! below sRGB 34 emits no light at all, which is most of a dark image. So the
//! table keeps four extra fractional bits: entry `q` means "this code wants
//! `q/16` of a level".
//!
//! * Without temporal dithering the firmware uses `q >> 4` and those 34 codes
//!   are black.
//! * With it (card 030) the remainder `q & 15` is spent across successive
//!   panel refreshes, and only sRGB 0 and 1 emit nothing.
//!
//! Brightness is deliberately **not** in this table. It is output-enable duty
//! in the framebuffer (see `vendor/README.md`), so dimming the panel does not
//! move a single entry here and costs no colour depth.

/// Bit-planes per channel, and therefore duty levels: `0..=63`.
pub const PLANES: usize = 6;
pub const LEVELS: u16 = (1 << PLANES) - 1; // 63

/// Fractional bits carried below one duty level.
pub const FRAC_BITS: u16 = 4;
pub const FRAC: u16 = 1 << FRAC_BITS; // 16

/// sRGB code -> panel duty in 1/16ths of a level, i.e. `0 ..= 63*16`.
