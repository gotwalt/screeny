/// The identity mapping, for A/B tests: sRGB code straight to a duty level,
/// truncated to [`PLANES`] bits. This is what the bring-up spike effectively
/// did, and it is what "gamma off" means in the test commands.
#[inline(always)]
pub fn linear_q(srgb: u8) -> u16 {
    (srgb as u16 >> (8 - PLANES as u16)) * FRAC
}

#[inline(always)]
pub fn gamma_q(srgb: u8) -> u16 {
    SRGB_TO_Q[srgb as usize]
}

const _: () = assert!(SRGB_TO_Q[255] as u16 == LEVELS * FRAC);
const _: () = assert!(SRGB_TO_Q[0] == 0);
