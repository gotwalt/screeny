//! Two bitmap fonts, because the status screen has 64x32 pixels to say a
//! device name, an IPv4 address and a signal strength in.
//!
//! [`FONT_5X7`] is the usual 5x7 cell (6 px pitch, so ten characters across a
//! 64-wide panel). [`FONT_3X5`] is digits and a dot only, at a 4 px pitch, so
//! that `192.168.7.221` fits on one line with room to spare.
//!
//! Glyphs are column-major: one byte per column, bit 0 the top row.

/// Columns per [`FONT_5X7`] glyph.
pub const W5: usize = 5;
/// Rows per [`FONT_5X7`] glyph.
pub const H5: usize = 7;
/// First character [`FONT_5X7`] covers.
pub const FIRST5: u8 = 0x20;

