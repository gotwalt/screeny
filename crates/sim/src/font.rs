/// Columns per [`FONT_3X5`] glyph.
pub const W3: usize = 3;
/// Rows per [`FONT_3X5`] glyph.
pub const H3: usize = 5;

/// A 3x5 glyph for one character, or `None` if this font has no such glyph.
/// Digits, `.` and `:` only - it exists to fit an IPv4 address on one row.
#[must_use]
pub fn glyph_3x5(c: char) -> Option<[u8; 3]> {
    Some(match c {
        '0' => [0x1F, 0x11, 0x1F],
        '1' => [0x12, 0x1F, 0x10],
        '2' => [0x1D, 0x15, 0x17],
        '3' => [0x15, 0x15, 0x1F],
        '4' => [0x07, 0x04, 0x1F],
        '5' => [0x17, 0x15, 0x1D],
        '6' => [0x1F, 0x15, 0x1D],
        '7' => [0x01, 0x01, 0x1F],
        '8' => [0x1F, 0x15, 0x1F],
        '9' => [0x17, 0x15, 0x1F],
        '.' => [0x00, 0x10, 0x00],
        ':' => [0x00, 0x0A, 0x00],
        '-' => [0x04, 0x04, 0x04],
        ' ' => [0x00, 0x00, 0x00],
        _ => return None,
    })
}

/// The 5x7 glyph for a character, falling back to `?` for anything outside
/// printable ASCII.
#[must_use]
pub fn glyph_5x7(c: char) -> [u8; 5] {
    let b = c as u32;
    if (FIRST5 as u32..=0x7E).contains(&b) {
        FONT_5X7[(b - FIRST5 as u32) as usize]
    } else {
        FONT_5X7[('?' as u32 - FIRST5 as u32) as usize]
    }
}

/// Width in pixels of `s` drawn in the 5x7 font at a 6 px pitch.
#[must_use]
pub fn width_5x7(s: &str) -> usize {
    match s.chars().count() {
        0 => 0,
        n => n * (W5 + 1) - 1,
    }
}

/// Width in pixels of `s` drawn in the 3x5 font at a 4 px pitch.
#[must_use]
pub fn width_3x5(s: &str) -> usize {
    match s.chars().count() {
        0 => 0,
        n => n * (W3 + 1) - 1,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Render a string the way the status screen does, as ASCII art, so the
    /// glyph table can be read by a human instead of trusted.
    fn art(s: &str) -> String {
        let mut rows = vec![String::new(); H5];
        for c in s.chars() {
            let g = glyph_5x7(c);
            for (y, row) in rows.iter_mut().enumerate() {
                for col in g {
                    row.push(if col >> y & 1 == 1 { '#' } else { '.' });
                }
                row.push('.');
            }
        }
        rows.join("\n")
    }

    #[test]
    fn the_font_table_is_the_right_shape() {
        assert_eq!(FONT_5X7.len(), (0x7E - 0x20 + 1) as usize);
        assert_eq!(glyph_5x7(' '), [0; 5]);
        assert_eq!(glyph_5x7('\u{263A}'), glyph_5x7('?'), "fallback");
        assert_eq!(width_5x7("abc"), 17);
        assert_eq!(width_5x7(""), 0);
        assert_eq!(width_3x5("192.168.7.221"), 51, "an IPv4 address fits in 64");
    }

    #[test]
    fn capital_a_looks_like_an_a() {
        assert_eq!(
            art("A"),
            [
                ".###..", //
                "#...#.", "#...#.", "#...#.", "#####.", "#...#.", "#...#.",
            ]
            .join("\n")
        );
    }

    #[test]
    fn digits_are_distinguishable() {
        // Every digit has a different bit pattern, in both fonts. A typo in
        // the table that duplicated a glyph would be invisible otherwise.
        let five: std::collections::BTreeSet<_> = ('0'..='9').map(glyph_5x7).collect();
        assert_eq!(five.len(), 10);
        let three: std::collections::BTreeSet<_> =
            ('0'..='9').map(|c| glyph_3x5(c).unwrap()).collect();
        assert_eq!(three.len(), 10);
    }

    #[test]
    fn tiny_font_covers_what_an_address_needs() {
        for c in "0123456789.:- ".chars() {
            assert!(glyph_3x5(c).is_some(), "{c:?}");
        }
        assert!(glyph_3x5('a').is_none());
        // Nothing may set a bit below row 5.
        for c in "0123456789.:-".chars() {
            for col in glyph_3x5(c).unwrap() {
                assert_eq!(col & !0x1F, 0, "{c:?} spills out of five rows");
            }
        }
    }

    #[test]
    fn nothing_in_the_5x7_font_spills_out_of_seven_rows() {
        for (i, g) in FONT_5X7.iter().enumerate() {
            for col in g {
                assert_eq!(
                    col & !0x7F,
                    0,
                    "glyph {:?} spills out of seven rows",
                    (FIRST5 + i as u8) as char
                );
            }
        }
    }
}
